#!/usr/bin/env bash
#
# Client/inspector helper for the autonomous-repair scenario (deploy/repair.sh).
#
# The scenario proves node-side repair end to end: a file is stored across the
# nodes (each shard carrying its stripe descriptor + a signed repair grant), one
# node is taken DOWN, and a *surviving* node — with NO client online — detects the
# degraded stripe and regenerates the lost shards onto a node that did not hold
# them, authorized purely by the grant. Any k of the shards then still rebuild the
# file.
#
# Subcommands (each a separate one-shot container so the orchestrator can stop a
# node in between):
#   store    — write a random file across all nodes and save its root/source.
#   snapshot — record every node's on-disk shard IDs to /handoff (the baseline).
#   verify   — after a node is down and repair has run, assert that a shard the
#              downed node held has reappeared on a survivor that lacked it.
#   get      — retrieve the file and assert it is byte-identical.
#
# A DiskStore lays a shard out at <mount>/shards/<xx>/<hash>, so a shard's file
# name IS its content address — listing them gives the exact shard-ID set a node
# holds, with no revika-ctl needed.
set -euo pipefail

: "${SEED_ADDR:?SEED_ADDR must point at the seed node /p2p multiaddr}"

SRC=/handoff/repair-src.bin
# The workspace lives on the shared /handoff volume so the post-failure `get`
# container reuses the same config.json (bootstrap) + root.json the `store`
# container wrote. Bootstrap is no longer a per-command flag; it comes from here.
WS=/handoff/repair-ws
ROOTFILE=/handoff/repair-ws/root.json
SIGNKEY=/handoff/repair-user.sign.key

# The node data volumes are mounted read-only here; the DOWN node is passed so
# verify knows which survivors to inspect. node4/node5 are spares in the repair
# scenario (they give repair an obviously-fresh target and cut colocation).
NODES=(seed node2 node3 node4 node5)
DOWN_NODE="${DOWN_NODE:-node3}"

# list_shards <node> prints the shard-ID (hash) set a node holds, one per line.
list_shards() {
  find "/nodes/$1/shards" -type f -printf '%f\n' 2>/dev/null | sort
}

retry() {
  local what="$1"; shift
  local n
  for n in 1 2 3 4 5 6; do
    if "$@"; then return 0; fi
    echo "   $what attempt $n failed; retrying in 5s..."
    sleep 5
  done
  return 1
}

case "${1:-}" in
  store)
    echo ">> [store] generating a 1 MiB file and storing it across all nodes"
    head -c 1048576 /dev/urandom >"$SRC"
    revika-ctl keygen -key /handoff/repair-user -pow-difficulty 0 >/dev/null
    revika-ctl connect -root "$WS" -bootstrap "$SEED_ADDR" -pow-difficulty 0 -force >/dev/null
    retry "store" revika-ctl cp -root "$WS" -signkey "$SIGNKEY" "$SRC" rvk:repair.bin \
      || { echo "FAIL: store never succeeded"; exit 1; }
    [ -s "$ROOTFILE" ] || { echo "FAIL: no root pointer written"; exit 1; }
    echo "OK: stored; root pointer + source saved under /handoff"
    ;;

  snapshot)
    echo ">> [snapshot] recording each node's shard set as the pre-failure baseline"
    for n in "${NODES[@]}"; do
      list_shards "$n" >"/handoff/before-$n.txt"
      echo "   $n holds $(wc -l <"/handoff/before-$n.txt" | tr -d ' ') shard(s)"
    done
    ;;

  verify)
    echo ">> [verify] checking a survivor regenerated a shard the downed node held"
    [ -s "/handoff/before-$DOWN_NODE.txt" ] || { echo "FAIL: no baseline for $DOWN_NODE (did 'snapshot' run?)"; exit 1; }

    # Shards the downed node held before it went away.
    downed=$(cat "/handoff/before-$DOWN_NODE.txt")

    # For each surviving node, the shards it has NOW that it did NOT have in the
    # baseline are freshly written — i.e. regenerated by repair. If any of those
    # is a shard the downed node held, repair demonstrably re-placed a lost shard
    # onto a node that lacked it, with no client online.
    regenerated=""
    for n in "${NODES[@]}"; do
      [ "$n" = "$DOWN_NODE" ] && continue
      new=$(comm -13 "/handoff/before-$n.txt" <(list_shards "$n"))
      if [ -n "$new" ]; then
        onto=$(comm -12 <(echo "$downed" | sort) <(echo "$new" | sort))
        if [ -n "$onto" ]; then
          echo "   $n regenerated shard(s) the downed node held:"
          echo "$onto" | sed 's/^/     /'
          regenerated="$regenerated $n"
        fi
      fi
    done

    if [ -z "$regenerated" ]; then
      echo "FAIL: no downed-node shard was regenerated onto a survivor"
      exit 1
    fi
    echo "PASS: autonomous repair re-placed lost shard(s) onto survivor(s):$regenerated"
    ;;

  get)
    echo ">> [get] retrieving the file after repair"
    [ -s "$ROOTFILE" ] || { echo "FAIL: /handoff root pointer missing (did 'store' run?)"; exit 1; }
    OUT=/tmp/repair-out.bin
    retry "get" revika-ctl cp -root "$WS" rvk:repair.bin "$OUT" \
      || { echo "FAIL: get never succeeded"; exit 1; }
    if cmp -s "$SRC" "$OUT"; then
      echo "PASS: file retrieved byte-identical after repair"
    else
      echo "FAIL: retrieved file differs from the original"
      exit 1
    fi
    ;;

  *)
    echo "usage: repair-client.sh {store|snapshot|verify|get}" >&2
    exit 2
    ;;
esac
